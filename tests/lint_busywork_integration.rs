// ─── Full default ruleset ────────────────────────────────────────────────────

#[test]
fn default_ruleset_has_five_rules() {
    let rules = default_rules();
    assert_eq!(rules.len(), 5, "v0 ruleset must have exactly 5 rules");
    let ids: Vec<&str> = rules.iter().map(|r| r.id()).collect();
    assert!(ids.contains(&"ABF-001"));
    assert!(ids.contains(&"ABF-002"));
    assert!(ids.contains(&"ABF-003"));
    assert!(ids.contains(&"ABF-004"));
    assert!(ids.contains(&"ABF-005"));
}

#[test]
fn clean_repo_produces_no_findings() {
    // No suspicious commits, small PR, real code changes
    let input = make_input(
        vec![
            "feat: implement swarm review CLI stub",
            "feat: add GoldenTrace provenance trailer",
        ],
        vec!["src/swarm.rs", "src/golden_trace.rs", "src/main.rs"],
        vec![
            "+ pub fn handle_review() {",
            "+     println!(\"stub\");",
            "+ }",
        ],
    );
    let findings = scan(&input, &default_rules());
    assert!(
        findings.is_empty(),
        "Clean synthetic repo should produce zero findings, got: {findings:?}"
    );
}

#[test]
fn severity_values_are_valid() {
    // Verify Severity::as_str returns the expected strings
    assert_eq!(Severity::Warning.as_str(), "warning");
    assert_eq!(Severity::Error.as_str(), "error");
    assert_eq!(Severity::Info.as_str(), "info");
}
